// Package capmatrix records capability verification results and renders the
// project's capability matrix. The matrix is generated from tests so it can
// never drift from reality — the fix for the v0.9 "documented capability is
// not actually wired" failure mode.
package capmatrix

import (
	"fmt"
	"io"
	"strings"
	"sync"
)

// Result is one capability check outcome.
type Result struct {
	Name   string `json:"name"`
	Passed bool   `json:"passed"`
	Detail string `json:"detail,omitempty"`
}

// Registry collects results. Safe for concurrent use.
type Registry struct {
	mu      sync.Mutex
	results []Result
}

// New returns an empty registry.
func New() *Registry { return &Registry{} }

// Check records a result.
func (r *Registry) Check(name string, passed bool, detail string) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.results = append(r.results, Result{Name: name, Passed: passed, Detail: detail})
}

// Results returns a copy of all recorded results.
func (r *Registry) Results() []Result {
	r.mu.Lock()
	defer r.mu.Unlock()
	out := make([]Result, len(r.results))
	copy(out, r.results)
	return out
}

// AllPassed reports whether every recorded capability passed.
func (r *Registry) AllPassed() bool {
	for _, res := range r.Results() {
		if !res.Passed {
			return false
		}
	}
	return true
}

// Render writes the matrix as Markdown.
func (r *Registry) Render(w io.Writer) error {
	results := r.Results()
	passed := 0
	for _, res := range results {
		if res.Passed {
			passed++
		}
	}
	var b strings.Builder
	b.WriteString("# Capability Matrix\n\n")
	b.WriteString("> Generated by `test/capability` — **do not edit by hand**.\n\n")
	fmt.Fprintf(&b, "Total: **%d**, passed: **%d**, failed: **%d**\n\n", len(results), passed, len(results)-passed)
	b.WriteString("| Capability | Status | Detail |\n")
	b.WriteString("|---|---|---|\n")
	for _, res := range results {
		status := "FAIL"
		if res.Passed {
			status = "PASS"
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", esc(res.Name), status, esc(res.Detail))
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func esc(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}
